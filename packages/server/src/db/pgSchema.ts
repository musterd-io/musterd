import { toPostgres } from './dialect.js';
import type { Driver } from './driver.js';
import { openDb } from './open.js';

/**
 * INTERIM — until plan 1B's Postgres migration ladder lands, at which point this file is deleted and
 * `loadPgSchema` runs that ladder. Today it derives the Postgres schema from the CURRENT SQLite
 * schema: open an in-memory better-sqlite3 db (which runs the whole ladder), read `sqlite_master`,
 * and translate the DDL with the spike's Q1 rules plus the four FTS5 hand-fixes. Those exact
 * statements loaded 106/106 on PGlite on 2026-09-29 (docs/perf/pglite-spike.md Q1).
 */

interface HandFix {
  why: string;
  match: RegExp;
  /** null drops the statement */
  replace: string | null;
}

/** All four are ONE feature: SQLite FTS5 has no Postgres equivalent (see teamMemory.ts). */
const HAND_FIXES: HandFix[] = [
  {
    why: 'FTS5 virtual table → tsvector table + GIN index',
    match: /^CREATE VIRTUAL TABLE insights_fts USING fts5/,
    replace: `CREATE TABLE insights_fts (
  message_id TEXT PRIMARY KEY, team_id TEXT NOT NULL, headline TEXT NOT NULL DEFAULT '',
  body TEXT NOT NULL DEFAULT '', tags TEXT NOT NULL DEFAULT '',
  tsv tsvector GENERATED ALWAYS AS (to_tsvector('english', headline || ' ' || body || ' ' || tags)) STORED
);
CREATE INDEX idx_insights_fts_tsv ON insights_fts USING GIN (tsv)`,
  },
  {
    why: 'FTS5 shadow tables have no counterpart',
    match: /^CREATE TABLE 'insights_fts_/,
    replace: null,
  },
  {
    why: 'SQLite trigger body → Postgres trigger function (insert)',
    match: /^CREATE TRIGGER insights_fts_ins/,
    replace: `CREATE FUNCTION insights_fts_ins_fn() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF NEW.act = 'insight' THEN
    INSERT INTO insights_fts (message_id, team_id, headline, body, tags)
    VALUES (NEW.id, NEW.team_id, COALESCE(NEW.meta::jsonb ->> 'headline', ''), NEW.body, COALESCE(NEW.meta::jsonb ->> 'tags', ''));
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER insights_fts_ins AFTER INSERT ON messages FOR EACH ROW EXECUTE FUNCTION insights_fts_ins_fn()`,
  },
  {
    why: 'SQLite trigger body → Postgres trigger function (delete)',
    match: /^CREATE TRIGGER insights_fts_del/,
    replace: `CREATE FUNCTION insights_fts_del_fn() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF OLD.act = 'insight' THEN DELETE FROM insights_fts WHERE message_id = OLD.id; END IF;
  RETURN OLD;
END $$;
CREATE TRIGGER insights_fts_del AFTER DELETE ON messages FOR EACH ROW EXECUTE FUNCTION insights_fts_del_fn()`,
  },
];

/** Split on `;` at line end, drop PRAGMAs and empties. Good enough for the DDL SQLite emits. */
function splitStatements(sql: string): string[] {
  return sql
    .split(/;\s*\n|;\s*$/)
    .map((s) => s.trim())
    .filter((s) => s && !/^PRAGMA\b/i.test(s));
}

function outsideLiterals(sql: string, fn: (code: string) => string): string {
  return sql
    .split(/('(?:[^']|'')*')/)
    .map((part, i) => (i % 2 ? part : fn(part)))
    .join('');
}

/** The DDL rewrite (spike Q1). `json_extract` in generated columns goes through the same translator
 *  the drivers use, so a path shape works in DDL iff it works in a query. */
function ddlToPostgres(ddl: string): string {
  const withJson = ddl.replace(/\bjson_extract\([^()]*\)/g, (m) => toPostgres(m));
  return outsideLiterals(withJson, (s) =>
    s
      .replace(
        /\bINTEGER PRIMARY KEY AUTOINCREMENT\b/g,
        'BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY',
      )
      .replace(/\bINTEGER PRIMARY KEY\b/g, 'BIGINT PRIMARY KEY')
      .replace(/\bINTEGER\b/g, 'BIGINT')
      .replace(/\bREAL\b/g, 'DOUBLE PRECISION')
      .replace(/\bBLOB\b/g, 'BYTEA')
      .replace(/\bWITHOUT ROWID\b/g, '')
      // Postgres 18 accepts VIRTUAL generated columns but refuses to index them; STORED indexes.
      .replace(/\)\s*VIRTUAL\b/g, ') STORED'),
  );
}

function applyHandFixes(statements: string[]): string[] {
  const out: string[] = [];
  for (const sql of statements) {
    const fix = HAND_FIXES.find((f) => f.match.test(sql));
    if (!fix) out.push(sql);
    else if (fix.replace !== null) out.push(fix.replace);
  }
  return out;
}

/** The current DDL out of a fully migrated in-memory SQLite db. Tables first, then the rest. */
function currentSqliteDdl(): string {
  const db = openDb(':memory:');
  try {
    return db
      .prepare<[], { sql: string }>(
        "SELECT sql FROM sqlite_master WHERE sql IS NOT NULL AND name NOT LIKE 'sqlite_%' ORDER BY CASE type WHEN 'table' THEN 0 ELSE 1 END, rowid",
      )
      .all()
      .map((r) => r.sql)
      .join(';\n');
  } finally {
    db.close();
  }
}

let memo: string[] | null = null;

/** The Postgres statements for the current schema, memoised per process. */
export function pgSchemaStatements(): string[] {
  if (!memo) memo = applyHandFixes(splitStatements(ddlToPostgres(currentSqliteDdl())));
  return memo;
}

/**
 * Load in passes: `sqlite_master` order is creation order, and a table rebuilt by a migration
 * (copy-drop-rename) lands AFTER the tables that reference it, so a single pass sees "relation does
 * not exist" for reasons that are ordering, not dialect. Retry until no progress; what is left failed
 * for a real reason and is thrown with every message.
 */
export async function loadPgSchema(d: Driver): Promise<void> {
  let pending = pgSchemaStatements().map((sql) => ({ sql, error: '' }));
  for (;;) {
    const next: typeof pending = [];
    for (const { sql } of pending) {
      try {
        // The statements are already Postgres text; the driver's translator is idempotent on it
        // (no `?`, no json_extract, no LIKE left to rewrite), so exec is safe here.
        await d.exec(sql);
      } catch (e) {
        next.push({ sql, error: String((e as Error)?.message ?? e) });
      }
    }
    if (next.length === 0) return;
    if (next.length === pending.length) {
      throw new Error(
        `pg schema: ${next.length} statement(s) failed:\n` +
          next.map((n) => `--- ${n.error}\n${n.sql.slice(0, 300)}`).join('\n'),
      );
    }
    pending = next;
  }
}
