// Q1 of the PGlite spike: does musterd's CURRENT schema (every migration applied) load on Postgres
// after a mechanical rewrite? Spike-only; the rewrite is deliberately dumb so the count of what it
// cannot fix is the finding.
//   pnpm --filter @musterd/server build && node scripts/perf/pglite-schema.mjs
import { PGlite } from '@electric-sql/pglite';

/**
 * Statement-specific fixes the mechanical rewrite could not generalise. Each is a Q1 hand-fix;
 * `replace: null` drops the statement. All four are ONE feature: SQLite FTS5 has no Postgres
 * equivalent, so `insights_fts` becomes a plain table with a generated `tsvector` + GIN index, its
 * five shadow tables go, and the two sync triggers become trigger functions.
 */
export const HAND_FIXES = [
  {
    why: 'FTS5 virtual table → tsvector table + GIN index',
    match: /^CREATE VIRTUAL TABLE insights_fts USING fts5/,
    replace: `CREATE TABLE insights_fts (
  message_id TEXT PRIMARY KEY, team_id TEXT NOT NULL, headline TEXT NOT NULL DEFAULT '',
  body TEXT NOT NULL DEFAULT '', tags TEXT NOT NULL DEFAULT '',
  tsv tsvector GENERATED ALWAYS AS (to_tsvector('english', headline || ' ' || body || ' ' || tags)) STORED
);
CREATE INDEX idx_insights_fts_tsv ON insights_fts USING GIN (tsv)`,
  },
  {
    why: 'FTS5 shadow tables have no counterpart',
    match: /^CREATE TABLE 'insights_fts_/,
    replace: null,
  },
  {
    why: 'SQLite trigger body → Postgres trigger function (insert)',
    match: /^CREATE TRIGGER insights_fts_ins/,
    replace: `CREATE FUNCTION insights_fts_ins_fn() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF NEW.act = 'insight' THEN
    INSERT INTO insights_fts (message_id, team_id, headline, body, tags)
    VALUES (NEW.id, NEW.team_id, COALESCE(NEW.meta::jsonb ->> 'headline', ''), NEW.body, COALESCE(NEW.meta::jsonb ->> 'tags', ''));
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER insights_fts_ins AFTER INSERT ON messages FOR EACH ROW EXECUTE FUNCTION insights_fts_ins_fn()`,
  },
  {
    why: 'SQLite trigger body → Postgres trigger function (delete)',
    match: /^CREATE TRIGGER insights_fts_del/,
    replace: `CREATE FUNCTION insights_fts_del_fn() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF OLD.act = 'insight' THEN DELETE FROM insights_fts WHERE message_id = OLD.id; END IF;
  RETURN OLD;
END $$;
CREATE TRIGGER insights_fts_del AFTER DELETE ON messages FOR EACH ROW EXECUTE FUNCTION insights_fts_del_fn()`,
  },
];

/** Split on `;` at line end, drop PRAGMAs and empties. Good enough for DDL SQLite emits. */
export function splitStatements(sql) {
  return sql
    .split(/;\s*\n|;\s*$/)
    .map((s) => s.trim())
    .filter((s) => s && !/^PRAGMA\b/i.test(s));
}

/** Apply `fn` to the text outside single-quoted literals only. */
function outsideLiterals(sql, fn) {
  return sql
    .split(/('(?:[^']|'')*')/)
    .map((part, i) => (i % 2 ? part : fn(part)))
    .join('');
}

export function sqliteToPostgres(ddl) {
  // json_extract carries its own quoted path, so it is rewritten on the whole text first; the
  // literal-aware pass below would never see the path.
  const withJson = ddl.replace(
    /\bjson_extract\(([^,()]+),\s*'\$\.([A-Za-z0-9_]+)'\)/g,
    "($1::jsonb ->> '$2')",
  );
  return outsideLiterals(withJson, (s) =>
    s
      .replace(
        /\bINTEGER PRIMARY KEY AUTOINCREMENT\b/g,
        'BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY',
      )
      .replace(/\bINTEGER PRIMARY KEY\b/g, 'BIGINT PRIMARY KEY')
      .replace(/\bINTEGER\b/g, 'BIGINT')
      .replace(/\bREAL\b/g, 'DOUBLE PRECISION')
      .replace(/\bBLOB\b/g, 'BYTEA')
      .replace(/\bWITHOUT ROWID\b/g, '')
      // Postgres 18 accepts VIRTUAL generated columns but refuses to index them; STORED indexes.
      .replace(/\)\s*VIRTUAL\b/g, ') STORED'),
  );
}

export function applyHandFixes(statements) {
  const out = [];
  for (const sql of statements) {
    const fix = HAND_FIXES.find((f) => f.match.test(sql));
    if (!fix) out.push(sql);
    else if (fix.replace !== null) out.push(fix.replace);
  }
  return out;
}

/**
 * Load in passes: SQLite's `sqlite_master` order is creation order, and a table rebuilt by a
 * migration (copy-drop-rename) lands AFTER the tables that reference it, so a single pass sees
 * "relation does not exist" for reasons that are ordering, not dialect. Retry until no progress;
 * what is left failed for a real reason.
 */
export async function loadSchema(pg, statements) {
  const ok = [];
  let pending = statements.map((sql) => ({ sql }));
  for (;;) {
    const next = [];
    for (const { sql } of pending) {
      try {
        await pg.exec(sql);
        ok.push(sql);
      } catch (e) {
        next.push({ sql, error: String(e?.message ?? e) });
      }
    }
    if (next.length === pending.length || next.length === 0) return { ok, failed: next };
    pending = next;
  }
}

/** Pull the current DDL out of a fully migrated in-memory SQLite db. Tables first, then indexes. */
export function currentSqliteDdl(db) {
  return db
    .prepare(
      "SELECT sql FROM sqlite_master WHERE sql IS NOT NULL AND name NOT LIKE 'sqlite_%' ORDER BY CASE type WHEN 'table' THEN 0 ELSE 1 END, rowid",
    )
    .all()
    .map((r) => r.sql)
    .join(';\n');
}

if (process.argv[1] && process.argv[1].endsWith('pglite-schema.mjs')) {
  const { openDb } = await import('../../packages/server/dist/index.js');
  const sqlite = openDb(':memory:');
  const ddl = currentSqliteDdl(sqlite);
  const stmts = applyHandFixes(splitStatements(sqliteToPostgres(ddl)));
  const tables = stmts.filter((s) => /^CREATE TABLE/i.test(s)).length;
  const pg = new PGlite();
  const r = await loadSchema(pg, stmts);
  console.log(
    `statements: ${stmts.length} (tables ${tables}, indexes ${stmts.length - tables}) · ok: ${r.ok.length} · failed: ${r.failed.length} · hand-fixes: ${HAND_FIXES.length}`,
  );
  for (const f of r.failed) console.log(`\n--- ${f.error}\n${f.sql.slice(0, 400)}`);
  await pg.close();
}
